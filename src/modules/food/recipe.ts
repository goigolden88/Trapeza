/**
 * Рецепт блюда — один текст по заготовке (Р-39).
 *
 * Ссылок на другие блюда нет: ингредиенты, выход и шаги — строки текста.
 * Калорийность из рецепта не считается; ИИ по промпту даёт оценку, и она
 * переносится руками в калорийность блюда (Р-03, Р-38).
 *
 * Заготовка и промпт живут здесь, а не буквами в разметке: поменяется вид —
 * поменяется в одном месте, и промпт с полем не разойдутся.
 */

/** Разделы, по которым пишется рецепт. Из них собирается и заготовка, и промпт. */
export const RECIPE_PARTS = ['Порций:', 'Время:', 'Ингредиенты', 'Как готовить', 'Заметки'] as const

/** Строки, которые сами по себе ещё не рецепт: заголовки заготовки и её маркеры. */
const SCAFFOLD: readonly string[] = [...RECIPE_PARTS, '-', '1.', '']

/** Пустая заготовка — её кладёт кнопка в форме блюда. */
export const RECIPE_TEMPLATE = ['Порций:', 'Время:', '', 'Ингредиенты', '-', '', 'Как готовить', '1.', '', 'Заметки', ''].join(
  '\n',
)

/**
 * Текст поля → рецепт блюда или «рецепта нет». Заготовка, в которой ничего
 * не написано, — не рецепт: иначе открытая и закрытая форма оставляла бы
 * блюду пустые заголовки.
 */
export function cleanRecipe(text: string): string | undefined {
  const lines = text.replace(/\r\n?/g, '\n').split('\n').map((line) => line.trimEnd())
  const written = lines.some((line) => !SCAFFOLD.includes(line.trim()))
  if (!written) return undefined
  const from = lines.findIndex((line) => line.trim() !== '')
  let to = lines.length
  while (to > from && lines[to - 1]?.trim() === '') to -= 1
  return lines.slice(from, to).join('\n')
}

/**
 * Промпт для ИИ: ответ приходит в том же виде, что и заготовка, и вставляется
 * в поле целиком. Оценка калорийности — последней строкой: её место в поле
 * блюда, а не в рецепте, и переносится она руками.
 */
export function recipePrompt(name: string): string {
  const dish = name.trim() || 'блюдо'
  return [
    'Ты помогаешь вести личный учёт еды.',
    '',
    `Напиши рецепт блюда «${dish}» ровно в таком виде — без разметки, без жирного шрифта и без лишних слов до и после:`,
    '',
    RECIPE_TEMPLATE.trimEnd(),
    '',
    'Правила:',
    '— «Порций» — сколько порций выходит, «Время» — сколько готовить.',
    '— В «Ингредиентах» — по строке на ингредиент, с количеством: «Свёкла — 300 г».',
    '— В «Как готовить» — шаги по порядку, коротко, каждый с новой строки.',
    '— В «Заметках» — чем можно заменить и на что смотреть, если нечего сказать — оставь пусто.',
    '— Последней строкой добавь оценку калорийности готового блюда: «≈ N ккал на 100 г».',
    '  Скажи, что это оценка: точного значения у домашнего блюда нет.',
    '',
    'Если рецепт я приложу свой — ничего не выдумывай сверх него, только приведи к этому виду.',
  ].join('\n')
}
