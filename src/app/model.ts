import type { Base, Migration } from '../shared/core/model.ts'

/**
 * Версия схемы. Растёт с каждым шагом в `migrations` — и с добавлением
 * хранилища тоже: IndexedDB заводит хранилище только при смене версии.
 */
export const SCHEMA_VERSION = 1

// ─── Справочники ───────────────────────────────────────────────────────────

/**
 * Категория: Каши, Супы особые, Мясное, Сладости, Сладкие напитки, Компот… (Р-15)
 * id — `cat:<название>` (Р-12)
 */
export type Category = Base & {
  name: string
  /** порядок в итогах дня и недели */
  order: number
  /** укрупнение для сводок: «Каши», «Пироги и сладости», «Напитки» (Р-15) */
  group?: string
  archived?: boolean
  /** у надгробия: куда слита или перенесена (Р-12) */
  movedTo?: string
}

/**
 * Блюдо или продукт: «Гречка», «Борщ», «Компот», «Сырок» — одна структура (Р-02, Р-07)
 * id — `dish:<название>` (Р-12)
 */
export type Dish = Base & {
  name: string
  /** нет — «без категории»; итоги называют, сколько таких (Р-02) */
  categoryId?: string
  /** вес порции по умолчанию */
  portionGrams?: number
  /** ккал на 100 г — справочно (Р-03) */
  kcal100?: number
  /** ккал на порцию — когда граммы не известны: «кофе с молоком» */
  kcalPortion?: number
  /** рецепт — один текст по заготовке (Р-39); необязательное поле — без миграции */
  recipe?: string
  archived?: boolean
  /** у надгробия: куда слито (Р-12) */
  movedTo?: string
}

/** Шаблон приёма — «обычный завтрак» — или дня — «обычный день». Заводится из записанного (Р-08, Р-28) */
export type Template = Base & {
  name: string
  /** есть — шаблон приёма; нет — шаблон дня, приём у каждого блюда */
  meal?: Meal
  items: { dishId: string; meal?: Meal; portions?: number; grams?: number }[]
  /** порядок внутри своего вида: шаблоны дня, шаблоны одного приёма */
  order: number
}

/** Норма недели над набором категорий: «Сладкое — не больше 4 дней» (Р-13) */
export type Norm = Base & {
  name: string
  categoryIds: string[]
  /** дней с записью — не меньше */
  minDays?: number
  /** дней с записью — не больше */
  maxDays?: number
  /** YYYY-MM-DD; нет — вся история (отступление от «Делу Время», Р-13) */
  since?: string
  order: number
}

// ─── Записи ────────────────────────────────────────────────────────────────

/** Съеденное: одно блюдо в одном приёме одного дня (Р-11) */
export type Intake = Base & {
  /** YYYY-MM-DD, день еды, не день ввода */
  date: string
  meal: Meal
  dishId: string
  /** нет — 1; дробные законны: «полпорции» */
  portions?: number
  /** правка порции граммами; есть — главнее portions */
  grams?: number
  /** ЧЧ:ММ, по желанию (Р-14) */
  at?: string
  /** «в кафе», «изжога» (Р-05, Р-15) */
  note?: string
  refs?: string[]
}

export type Meal = 'breakfast' | 'lunch' | 'dinner' | 'snack'

/** Вид записи. Одно значение — ровно то, что описано выше. */
export type RecordKind = 'intake'

// ─── Хранилища ─────────────────────────────────────────────────────────────

/**
 * Хранилища, которые уезжают в синхронизацию. Имена совпадают с раскладкой
 * в репозитории данных (02-Архитектура, «Локальное хранилище»).
 * Менять имена нельзя — они в базе на устройстве. Порядок — тот, в котором
 * пишут импорт и слепок: справочники раньше записей, что на них ссылаются.
 */
export const SYNCED_STORES = ['categories', 'dishes', 'templates', 'norms', 'intake'] as const

export type SyncedStore = (typeof SYNCED_STORES)[number]

/**
 * Что лежит в каком хранилище. Позволяет db.get('intake') возвращать Intake;
 * это и есть таблица `R` для `AppConfig<R>` ядра.
 */
export type StoreRecord = {
  categories: Category
  dishes: Dish
  templates: Template
  norms: Norm
  intake: Intake
}

