/** «7 дней», «6 дней», «1 дня» — после «до». */
function daysOf(count: number): string {
  return `${count} ${plural(count, ['дня', 'дней', 'дней'])}`
}

/** «3 недель», «8 недель» — после «с» и «последних». */
function weeksOf(count: number): string {
  return `${count} ${plural(count, ['недели', 'недель', 'недель'])}`
}

/** «20 таких приёмов», «21 такого приёма» — после «последних». */
function mealsOf(count: number): string {
  return `${count} ${plural(count, ['такого приёма', 'таких приёмов', 'таких приёмов'])}`
}

